'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
function section(start, end) {
  const a = source.indexOf(start);
  const b = source.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error('Arena extraction markers changed; review index.html first.');
  return source.slice(a, b).trimEnd();
}
const header = "/* =====================================================================\n   DAMAGE TYPE LABELS";
let core = section('const LANG = {', header);
const language = "let currentLang = localStorage.getItem('arena_lang') || 'zh';";
if (!core.includes(language)) throw new Error('Language initialization changed.');
core = core.replace(language, "let currentLang = 'zh'; // Server-side language, no DOM/localStorage.");
// Only the adventure copy changes: original arena modes retain their exact source.
const random = "!target.conditions.has('stunned')&&Math.random()<0.4";
if (!core.includes(random)) throw new Error('Review Stunning Strike RNG adaptation.');
core = core.replace(random, "!target.conditions.has('stunned')&&eng.rng()<0.4");
// BOSSES/createBossCharacter remain verbatim source, but are not exported or used by the prototype.
const digest = crypto.createHash('sha256').update(source).digest('hex');
const result = `// GENERATED by scripts/extract-arena.cjs. Edit index.html or the extractor, then regenerate.\n// index.html SHA-256: ${digest}\n'use strict';\n${core}\n\nmodule.exports = { NameHasher, Character, CombatEngine, CLASSES, SUBCLASSES, mod };\n`;
const destination = path.join(root, 'adventure/lib/arena.cjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== result) {
    throw new Error('Generated arena module is stale. Run npm run engine:extract and review the diff.');
  }
  console.log('Arena module matches index.html and documented adaptations.');
} else {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, result);
  console.log('Extracted existing character, dice, class data and combat engine.');
}
